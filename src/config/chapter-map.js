export function normalizeAcademicString(str) {
  if (!str) return "";
  return String(str)
    .normalize('NFC')
    .toLowerCase()
    .replace(/[০-৯]/g, d => BN_TO_EN_DIGITS[d] || d)
    // Keep Bengali Anusvara (ং is \u0982), strip Visarga (ঃ is \u0983), colons, hyphens, dashes, and punctuation
    .replace(/[\u0983:;,\–\—\-_।/\\()\[\]{}'"`?*!+~@#$%^&=|]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}
